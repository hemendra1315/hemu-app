CREATE OR REPLACE FUNCTION public.record_academy_record(p_academy uuid, p_record record_type, p_player uuid, p_match uuid, p_value_num numeric, p_value_txt text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if auth.uid() is not null and not is_staff(p_academy) then
    raise exception 'E_FORBIDDEN' using errcode = '42501';
  end if;

  if p_value_num is null and p_value_txt is null then
    return;
  end if;

  begin
    insert into academy_records (academy_id, record_type, player_id, match_id, value_numeric, value_text)
    values (p_academy, p_record, p_player, p_match, p_value_num, p_value_txt);
  exception
    when unique_violation then
      if p_value_num is not null then
        update academy_records
        set player_id = p_player, match_id = p_match, value_numeric = p_value_num, value_text = p_value_txt, achieved_at = now()
        where academy_id = p_academy and record_type = p_record
          and (value_numeric is null or p_value_num > value_numeric);
      end if;
  end;
end $function$
;

CREATE OR REPLACE FUNCTION public.redeem_parent_linking_code(p_code text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_code_record parent_linking_codes;
  v_academy_member_id uuid;
BEGIN
  SELECT * INTO v_code_record
  FROM parent_linking_codes
  WHERE code = upper(p_code)
    AND is_active = TRUE
    AND expires_at > now()
  FOR UPDATE;

  IF v_code_record.id IS NULL THEN
    RAISE EXCEPTION 'E_INVALID_CODE' USING errcode = 'P0002';
  END IF;

  UPDATE parent_linking_codes SET is_active = FALSE WHERE id = v_code_record.id;

  IF NOT EXISTS (
    SELECT 1 FROM academy_members 
    WHERE academy_id = v_code_record.academy_id 
      AND user_id = auth.uid()
      AND role = 'parent'
  ) THEN
    INSERT INTO academy_members (academy_id, user_id, role, status, joined_at)
    VALUES (v_code_record.academy_id, auth.uid(), 'parent', 'active', now());
  END IF;

  INSERT INTO parent_player_links (
    parent_user_id, player_user_id, academy_id, relationship_type, status
  ) VALUES (
    auth.uid(), v_code_record.player_user_id, v_code_record.academy_id, v_code_record.relationship_type, 'active'
  ) ON CONFLICT (parent_user_id, player_user_id, academy_id) 
  DO UPDATE SET status = 'active', relationship_type = EXCLUDED.relationship_type;

  RETURN v_code_record.academy_id;
END $function$
;

CREATE OR REPLACE FUNCTION public.refresh_academy_records(p_academy uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if auth.uid() is not null and not is_staff(p_academy) then
    raise exception 'E_FORBIDDEN' using errcode = '42501';
  end if;

  perform record_academy_record(
    p_academy, 'highest_team_score',
    null,
    null,
    (select max((split_part(team_score, '/', 1))::integer) from matches
     where academy_id = p_academy and status = 'completed' and team_score is not null
