    jsonb_agg(
      jsonb_build_object(
        'id', b.id,
        'name', b.name,
        'description', b.description
      )
    ),
    '[]'::jsonb
  ) INTO v_batches
  FROM batches b
  WHERE b.academy_id = p_academy_id;

  SELECT coalesce(
